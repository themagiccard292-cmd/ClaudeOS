#!/usr/bin/env python3
"""Generate etc/skel/.config/gtk-{3,4}.0/gtk.css from tokens.json.

Design facts (checked against GTK 3.24.52, GTK 4.22.4 and libadwaita 1.9.0 sources):

* The user stylesheet is ``~/.config/gtk-{3,4}.0/gtk.css`` only.  A user ``gtk-dark.css`` is
  never loaded by GTK or libadwaita, so no such file is shipped.
* GTK 4.20+ evaluates ``@media (prefers-color-scheme: dark)`` in the user stylesheet (it is
  bound to ``gtk-interface-color-scheme``, which libadwaita drives) and accepts
  ``@define-color`` inside it, exactly as libadwaita's own ``_colors.scss`` does.  So the
  GTK 4 file holds the light palette plus a dark ``@media`` block.
* GTK 3 has no ``@media``.  Its file therefore only overrides colours that are identical in
  both schemes (the terracotta selection accent); surfaces keep following Yaru / Yaru-dark.

The first line is a marker carrying the sha256 of the rest of the file; ``theme-apply`` uses
it to tell a pristine ClaudeOS file from one the user edited.

Usage: gen_gtk_css.py [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "usr/share/claudeos/theme/tokens.json"
MARKER = "claudeos-theme:managed"


def load_tokens() -> dict:
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def libadwaita_colors(t: dict, scheme: str) -> dict[str, str]:
    p = t[scheme]
    bg, surface, border, text = p["background"], p["surface"], p["border"], p["text"]
    return {
        # accent_color is the accent as *text/links on a window*; it needs more contrast
        # than the raw accent (see derived.accent-text in tokens.json).
        "accent_color": t["derived"]["accent-text"][scheme],
        "accent_bg_color": t["accent"],
        "accent_fg_color": t["derived"]["on-accent"],
        "window_bg_color": bg,
        "window_fg_color": text,
        "view_bg_color": surface,
        "view_fg_color": text,
        "headerbar_bg_color": bg,
        "headerbar_fg_color": text,
        "headerbar_backdrop_color": bg,
        "headerbar_shade_color": border,
        "sidebar_bg_color": bg,
        "sidebar_fg_color": text,
        "sidebar_backdrop_color": bg,
        "sidebar_border_color": border,
        "secondary_sidebar_bg_color": bg,
        "secondary_sidebar_fg_color": text,
        "secondary_sidebar_backdrop_color": bg,
        "secondary_sidebar_border_color": border,
        "card_bg_color": surface,
        "card_fg_color": text,
        "card_shade_color": border,
        "dialog_bg_color": bg,
        "dialog_fg_color": text,
        "popover_bg_color": surface,
        "popover_fg_color": text,
    }


def classic_colors(t: dict, scheme: str) -> dict[str, str]:
    """Classic GTK names, used by Yaru's GTK 4 theme for non-libadwaita apps."""
    p = t[scheme]
    bg, surface, border, text, muted = (p[k] for k in ("background", "surface", "border", "text", "text-muted"))
    accent, on_accent = t["accent"], t["derived"]["on-accent"]
    return {
        "theme_bg_color": bg,
        "theme_fg_color": text,
        "theme_base_color": surface,
        "theme_text_color": text,
        "theme_selected_bg_color": accent,
        "theme_selected_fg_color": on_accent,
        "theme_unfocused_bg_color": bg,
        "theme_unfocused_fg_color": muted,
        "theme_unfocused_base_color": surface,
        "theme_unfocused_text_color": text,
        "theme_unfocused_selected_bg_color": accent,
        "theme_unfocused_selected_fg_color": on_accent,
        "insensitive_bg_color": bg,
        "insensitive_fg_color": muted,
        "insensitive_base_color": surface,
        "borders": border,
        "unfocused_borders": border,
        "content_view_bg": surface,
        "text_view_bg": surface,
    }


def gtk3_colors(t: dict) -> dict[str, str]:
    accent, on_accent = t["accent"], t["derived"]["on-accent"]
    return {
        "theme_selected_bg_color": accent,
        "theme_selected_fg_color": on_accent,
        "theme_unfocused_selected_bg_color": accent,
        "theme_unfocused_selected_fg_color": on_accent,
    }


def defines(colors: dict[str, str], indent: str = "") -> str:
    return "\n".join(f"{indent}@define-color {name} {value};" for name, value in colors.items())


def with_marker(body: str) -> str:
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"/* {MARKER} sha256={digest} */\n{body}"


def gtk4_css(t: dict) -> str:
    light = {**libadwaita_colors(t, "light"), **classic_colors(t, "light")}
    dark = {**libadwaita_colors(t, "dark"), **classic_colors(t, "dark")}
    body = f"""/*
 * ClaudeOS warm palette for GTK 4 / libadwaita.
 * Generated by theme/scripts/gen_gtk_css.py from tokens.json. Do not edit: theme-apply
 * backs this file up and replaces it when it has been modified.
 *
 * Light values first; the media block mirrors how libadwaita itself switches schemes.
 */

{defines(light)}

@media (prefers-color-scheme: dark) {{
{defines(dark, "  ")}
}}

/* Restrained corner tweak. Buttons, entries and boxed lists are left alone on purpose:
   .circular, .pill, .linked and list rows rely on their own radii. */
.card,
popover > contents {{
  border-radius: 14px;
}}
"""
    return with_marker(body)


def gtk3_css(t: dict) -> str:
    body = f"""/*
 * ClaudeOS accent for GTK 3 apps (Yaru theme).
 * Generated by theme/scripts/gen_gtk_css.py from tokens.json. Do not edit: theme-apply
 * backs this file up and replaces it when it has been modified.
 *
 * GTK 3 cannot switch user CSS by colour scheme, so only colours that are the same in light
 * and dark are overridden; surfaces keep following Yaru / Yaru-dark.
 */

{defines(gtk3_colors(t))}
"""
    return with_marker(body)


def outputs() -> dict[Path, str]:
    t = load_tokens()
    skel = ROOT / "etc/skel/.config"
    return {skel / "gtk-4.0/gtk.css": gtk4_css(t), skel / "gtk-3.0/gtk.css": gtk3_css(t)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = 0
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
                stale += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
