# shellcheck shell=bash
# Stages 3 and 4: extract the ISO tree and merge the layered casper root filesystem.
#
# Ubuntu 26.04 desktop ISOs ship the root filesystem as stacked squashfs layers
# (minimal -> minimal.standard -> minimal.standard.live, plus language and enhanced-secureboot
# variants). casper derives a layer's parents by stripping the last dot-suffix, so the chain
# for "minimal.standard.live" is minimal.standard.live, minimal.standard, minimal.

# layer_chain TOP: print the layer chain topmost first (casper's parent rule).
layer_chain() {
  local layer="$1"
  while [[ -n "$layer" ]]; do
    printf '%s\n' "$layer"
    [[ "$layer" == *.* ]] || break
    layer="${layer%.*}"
  done
}

# overlay_lowerdir MOUNTROOT TOP: "M/top:M/parent:...:M/base" for a read-only overlay mount.
overlay_lowerdir() {
  local root="$1" top="$2" out="" l
  while IFS= read -r l; do
    out+="${out:+:}${root}/${l}"
  done < <(layer_chain "$top")
  printf '%s\n' "$out"
}

# overlay_supported: kernel has overlayfs (listed, or loadable).
overlay_supported() {
  grep -qw overlay /proc/filesystems 2>/dev/null || modprobe -q overlay 2>/dev/null
}

# Paths inside $WORK_DIR used by several stages.
iso_tree() { printf '%s/iso\n' "$WORK_DIR"; }
rootfs_dir() { printf '%s/rootfs\n' "$WORK_DIR"; }
layers_mnt() { printf '%s/layers\n' "$WORK_DIR"; }

# ------------------------------------------------------------------ stage 3: extract
stage_extract() {
  local tree
  tree="$(iso_tree)"
  if ! is_dry_run && [[ -d "$tree" ]]; then
    safe_rm_rf "$WORK_DIR" "$tree"
  fi
  run mkdir -p "$tree"
  run xorriso -osirrox on -indev "$SOURCE_ISO" -extract / "$tree"
  # Files come out with the ISO's read-only modes; we must be able to edit and delete them.
  run chmod -R u+rwX "$tree"
  # boot.catalog is regenerated by xorriso on repack; it is never part of the tree we edit.
  run rm -f "$tree/boot.catalog"
  record_boot_file_hashes
}

# Remember vmlinuz/initrd hashes so later stages can prove they are untouched.
boot_hash_file() { printf '%s/casper-boot-files.sha256\n' "$WORK_DIR"; }
record_boot_file_hashes() {
  local tree
  tree="$(iso_tree)"
  if is_dry_run; then
    run_to "$(boot_hash_file)" sha256sum "$tree/casper/vmlinuz" "$tree/casper/initrd"
    return 0
  fi
  [[ -f "$tree/casper/vmlinuz" && -f "$tree/casper/initrd" ]] || die "ISO has no casper/vmlinuz + casper/initrd"
  (cd "$tree" && sha256sum casper/vmlinuz casper/initrd) >"$(boot_hash_file)"
}

# assert_boot_files_unchanged DIR: DIR/casper/{vmlinuz,initrd} are byte-identical to the originals.
assert_boot_files_unchanged() {
  local dir="$1"
  if is_dry_run; then
    printf '+ (cd %q && sha256sum -c %q)\n' "$dir" "$(boot_hash_file)"
    return 0
  fi
  (cd "$dir" && sha256sum --quiet -c "$(boot_hash_file)") || die "casper/vmlinuz or casper/initrd changed - the kernel must stay in sync"
}

# ------------------------------------------------------------------ stage 4: rootfs
stage_rootfs() {
  local tree rootfs mnt top
  tree="$(iso_tree)"
  rootfs="$(rootfs_dir)"
  mnt="$(layers_mnt)"
  top="$ROOTFS_TOP_LAYER"

  local layers=()
  mapfile -t layers < <(layer_chain "$top")
  local l
  if ! is_dry_run; then
    for l in "${layers[@]}"; do
      [[ -f "$tree/casper/$l.squashfs" ]] || die "missing layer casper/$l.squashfs in the ISO"
    done
    if [[ -d "$rootfs" ]]; then safe_rm_rf "$WORK_DIR" "$rootfs"; fi
  fi
  log_info "layer chain (top first): ${layers[*]} - language and enhanced-secureboot layers are dropped"
  run mkdir -p "$rootfs"

  if is_dry_run || overlay_supported; then
    for l in "${layers[@]}"; do
      run mkdir -p "$mnt/$l"
      mount_tracked "$mnt/$l" -t squashfs -o loop,ro "$tree/casper/$l.squashfs"
    done
    run mkdir -p "$mnt/merged"
    mount_tracked "$mnt/merged" -t overlay overlay -o "ro,lowerdir=$(overlay_lowerdir "$mnt" "$top")"
    run rsync -aHAXx --numeric-ids "$mnt/merged/" "$rootfs/"
    if ! is_dry_run; then
      unmount_all || die "could not unmount the layer mounts"
    fi
  else
    log_warn "overlayfs is unavailable: unpacking layers with unsquashfs and applying whiteouts manually"
    local bottom_first=() i
    for ((i = ${#layers[@]} - 1; i >= 0; i--)); do
      run unsquashfs -f -d "$mnt/${layers[$i]}" "$tree/casper/${layers[$i]}.squashfs"
      bottom_first+=("$mnt/${layers[$i]}")
    done
    run python3 "$ISO_BUILDER_DIR/lib/flatten_layers.py" "$rootfs" "${bottom_first[@]}"
  fi
  if ! is_dry_run; then
    safe_rm_rf "$WORK_DIR" "$mnt"
    [[ -e "$rootfs/usr/bin/dpkg" ]] || die "merged rootfs has no /usr/bin/dpkg - layer merge failed"
  fi
}
